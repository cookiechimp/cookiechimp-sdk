import { readFile, rename, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";

const reactCss = new URL("../../react/styles.css", import.meta.url).pathname;

async function inline(file) {
  const css = await readFile(file, "utf8");
  let output = "";
  let offset = 0;
  for (const match of css.matchAll(/@import\s+["']([^"']+)["']\s*;/g)) {
    output += css.slice(offset, match.index);
    const path =
      match[1] === "@cookiechimp/tokens/css"
        ? new URL("../../tokens/dist/tokens.css", import.meta.url).pathname
        : match[1].startsWith(".")
          ? resolve(dirname(file), match[1])
          : createRequire(file).resolve(match[1]);
    output += await inline(path);
    offset = match.index + match[0].length;
  }
  return output + css.slice(offset);
}

const css = (await inline(reactCss)).replace(/\/\*[\s\S]*?\*\//g, "");

function blocks(source) {
  const result = [];
  let start = 0;
  while (start < source.length) {
    const open = source.indexOf("{", start);
    if (open < 0) break;
    let depth = 1;
    let quote = "";
    let close = open + 1;
    for (; close < source.length && depth; close++) {
      const character = source[close];
      if (quote) {
        if (character === "\\") close++;
        else if (character === quote) quote = "";
      } else if (character === '"' || character === "'") quote = character;
      else if (character === "{") depth++;
      else if (character === "}") depth--;
    }
    if (depth) throw new Error("Unbalanced CSS block");
    result.push({
      prelude: source.slice(start, open).trim().replace(/^.*;/s, "").trim(),
      body: source.slice(open + 1, close - 1),
    });
    start = close;
  }
  return result;
}

const wanted = (selector) =>
  /(?:^|,)\s*(?::root|\[data-cc-theme)/.test(selector) ||
  /\.(?:cc-banner|cc-title|cc-description|cc-actions|cc-button)(?:\b|[-_:])/.test(
    selector,
  );

function select(source) {
  return blocks(source)
    .map(({ prelude, body }) => {
      if (prelude.startsWith("@")) {
        const children = select(body);
        return children ? `${prelude}{${children}}` : "";
      }
      return wanted(prelude) ? `${prelude}{${body}}` : "";
    })
    .filter(Boolean)
    .join("\n");
}

const critical = select(css).replace(/\s+/g, " ").trim();
const quote = (value) =>
  `'${value.replaceAll("\\", "\\\\").replaceAll("'", "\\'").replaceAll("\n", "\\n")}'`;
if (
  !/(?:^|\s):root\s*{[^}]*--cc-banner-bg:/.test(critical) ||
  !critical.includes("position: fixed") ||
  !critical.includes("@media (max-width: 640px)")
)
  throw new Error(
    "Critical CSS generation did not find tokens, banner layout, and responsive context",
  );
const destination = new URL(
  "../src/critical-css.generated.ts",
  import.meta.url,
);
const generated = `// Generated by scripts/generate-critical-css.mjs. Do not edit.\nexport const criticalCss =\n  ${quote(critical)};\nexport const fullCss =\n  ${quote(css)};\n`;
let current;
try {
  current = await readFile(destination, "utf8");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
if (current !== generated) {
  const temporary = new URL(
    `critical-css.generated.ts.${process.pid}.${crypto.randomUUID()}.tmp`,
    destination,
  );
  try {
    await writeFile(temporary, generated, "utf8");
    await rename(temporary, destination);
  } finally {
    await rm(temporary, { force: true });
  }
}
